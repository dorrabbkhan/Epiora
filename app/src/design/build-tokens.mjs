#!/usr/bin/env node
// Generates app/src/design/tokens.css from tokens.json (spec §9.1).
// Output is deterministic: fixed order, fixed formatting, so the
// committed file can be diff-checked (check-app.sh, tokens.test.ts).
//
//   node src/design/build-tokens.mjs [output.css]
//
// With no argument it writes tokens.css next to this script.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const out = process.argv[2] ?? join(here, 'tokens.css');

const COLOR_SCHEME = {
  light: 'light',
  dark: 'dark',
  'hc-light': 'light',
  'hc-dark': 'dark',
};

function groupDeclarations(group, prefix, theme) {
  return Object.keys(tokens[group])
    .sort()
    .map((name) => {
      const entry = tokens[group][name];
      const value = theme === undefined ? entry : entry[theme];
      return `  --${prefix}-${name}: ${value};`;
    })
    .join('\n');
}

function themeBlock(selector, theme) {
  const lines = [
    `  color-scheme: ${COLOR_SCHEME[theme]};`,
    groupDeclarations('color', 'color', theme),
  ];
  return `${selector} {\n${lines.join('\n')}\n}`;
}

const flatGroups = ['space', 'radius', 'font', 'motion', 'focus'];
const rootBlock = `:root {\n${flatGroups
  .map((group) => groupDeclarations(group, group))
  .join('\n')}\n}`;

const zeroMotion = Object.keys(tokens.motion)
  .sort()
  .map((name) => `  --motion-${name}: 0ms;`)
  .join('\n');

const css = `/* GENERATED by build-tokens.mjs from tokens.json — do not edit. */

/* Theme-independent tokens. */
${rootBlock}

/* Explicit theme choice (Settings or a stored preference). */
${themeBlock(':root[data-theme="light"]', 'light')}

${themeBlock(':root[data-theme="dark"]', 'dark')}

${themeBlock(':root[data-theme="hc-light"]', 'hc-light')}

${themeBlock(':root[data-theme="hc-dark"]', 'hc-dark')}

/* No explicit theme: system preference chooses the default. */
${themeBlock(':root:not([data-theme])', 'light')}

@media (prefers-color-scheme: dark) {
${themeBlock('  :root:not([data-theme])', 'dark')}
}

@media (prefers-contrast: more) {
${themeBlock('  :root:not([data-theme])', 'hc-light')}
}

@media (prefers-contrast: more) and (prefers-color-scheme: dark) {
${themeBlock('  :root:not([data-theme])', 'hc-dark')}
}

@media (prefers-reduced-motion: reduce) {
  :root {
${zeroMotion}
  }
}

*, *::before, *::after {
  box-sizing: border-box;
}

body {
  margin: 0;
  background: var(--color-bg);
  color: var(--color-text);
  font-family: var(--font-familySans);
  font-size: var(--font-size3);
  line-height: var(--font-lineHeight);
}

.visually-hidden {
  position: absolute;
  width: 1px;
  height: 1px;
  padding: 0;
  margin: -1px;
  overflow: hidden;
  clip: rect(0 0 0 0);
  white-space: nowrap;
  border: 0;
}
`;

writeFileSync(out, css);
console.log(`wrote ${out}`);
