// app/scripts/validation-report-v1.mjs — the v1.0 validation report
// (v1.0 plan Task 21, platform spec §12.10). `buildReportV1(input)`
// renders docs/validation/v1.0.md from a source `app` workflow run's
// perf artifacts and job log plus the same commit's `engine`,
// `import` and `r-export` runs: every registry statistic with its
// references, class and worst error (the engine run's
// `v1.0-validation-json` artifact), the EI7/OpenEpi check counts (its
// `v0.2-validation-md` artifact), the r-export compare line, the
// Stata status, explain coverage, the gates (`means_1m`, the v0.3
// gates, engine wasm size, first load), axe results, and the G5
// pending sign-offs. Every number is parsed from CI output — nothing
// is typed in. The parsers it shares with the v0.3 report come from
// validation-report.mjs.

import {
  cell,
  clean,
  fmt,
  parseAttemptFacts,
  parseAxe,
  parseBudget,
  parseGates,
  parseSummary,
  parseWasmLimit,
} from './validation-report.mjs';

/** engine `v0.2-validation-md` → header + EI7/OpenEpi check counts. */
function parseEngineMd(md) {
  const wasm =
    /`gzip -9`: ([\d,]+|not measured) bytes \(budget ([\d,]+)\)/.exec(md);
  const bench =
    /Chromium bench median[^:]*: ([\d,.]+|not measured) ms \(budget < ([\d,]+) ms\)/.exec(
      md,
    );
  const ei7 =
    /`ei7\/oswego\.json` \(Epi Info ([^)]+)\): ([\d,]+) printed values mapped to engine keys, (\d+) mismatch/.exec(
      md,
    );
  const openepi =
    /`openepi\/\*\.json`: ([\d,]+) displayed values mapped to engine statistics across ([\d,]+) calculators, (\d+) mismatch[\s\S]*?(\d+) documented method difference/.exec(
      md,
    );
  const num = (s) => +s.replace(/,/g, '');
  return {
    wasmBytes: wasm === null || wasm[1] === 'not measured' ? null : num(wasm[1]),
    wasmBudget: wasm === null ? null : num(wasm[2]),
    benchMs: bench === null || bench[1] === 'not measured' ? null : num(bench[1]),
    benchBudget: bench === null ? null : num(bench[2]),
    ei7:
      ei7 === null
        ? null
        : { version: ei7[1], mapped: ei7[2], mismatches: +ei7[3] },
    openepi:
      openepi === null
        ? null
        : {
            mapped: openepi[1],
            calculators: num(openepi[2]),
            mismatches: +openepi[3],
            differences: +openepi[4],
          },
  };
}

/** r-export job log → {scripts, checked, mismatches}. */
function parseRExport(log) {
  const ran = /r-export: ran (\d+) scripts/.exec(log);
  const verified = /compare: (\d+) statistics verified/.exec(log);
  const failed = /compare: (\d+) failures/.exec(log);
  return {
    scripts: ran === null ? null : +ran[1],
    checked: verified === null ? null : +verified[1],
    mismatches: failed === null ? 0 : +failed[1],
  };
}

/** worst_error: `0`, `d.dde±n` like the Rust report's `{:.2e}`,
 *  `inf` when a leaf is not the reference's kind, `not measured`
 *  when the JSON omits the key. */
const fmtWorst = (s) => {
  if (!('worst_error' in s)) return 'not measured';
  if (s.worst_error === null) return 'inf';
  if (s.worst_error === 0) return '0';
  return Number(s.worst_error).toExponential(2).replace('e+', 'e');
};

const e2ePassedCount = (log) => {
  for (const raw of log.split('\n')) {
    const m = /^(\d+) passed \(/.exec(clean(raw).trim());
    if (m) return +m[1];
  }
  return null;
};

export function buildReportV1(input) {
  const { source } = input;
  const gates = parseGates(input.gatesMd);
  const summary = parseSummary(input.summaryMd);
  const axe = parseAxe(input.appJobLog);
  const budget = parseBudget(input.appJobLog);
  const wasmLimit = parseWasmLimit(input.importRun.jobLog);
  const eng = parseEngineMd(input.engineRun.validationMd);
  const json = input.engineRun.validationJson;
  const rexport = parseRExport(input.rExportRun.jobLog);
  const e2ePassed = e2ePassedCount(input.appJobLog);
  const gateOf = (name) => gates.find((g) => g.scenario === name);

  const out = [];
  out.push('# Epiora v1.0 validation report');
  out.push('');
  out.push(
    'Generated by `app/scripts/validation-report.mjs` (v1.0 Task 21, platform spec §12.10). Every',
    'number below is read from the named CI runs’ artifacts and job logs — nothing is typed in.',
    '',
    `- Commit: \`${source.sha}\``,
    `- Source run: ${source.url} — \`${source.workflow}\` workflow, \`${source.event}\`,`,
    `  attempt ${source.attempt}, conclusion **${source.conclusion}**. Perf results exist only on`,
    '  main-push and manual runs, so this report reads the `main` push run for the commit,',
    '  not a pull-request run.',
    input.generatedByUrl === null
      ? '- Generated by: local invocation (no CI run).'
      : `- Generated by CI run: ${input.generatedByUrl} — the run that produced this file.`,
    `- Sibling runs at this commit: \`engine\` ${input.engineRun.url} (conclusion`,
    `  ${input.engineRun.conclusion}); \`import\` ${input.importRun.url} (conclusion`,
    `  ${input.importRun.conclusion}); \`r-export\` ${input.rExportRun.url} (conclusion`,
    `  ${input.rExportRun.conclusion}).`,
    `- Corpus measurements: the \`engine\` run’s \`v1.0-validation-json\` and`,
    `  \`v0.2-validation-md\` artifacts (engine_version \`${json.engine_version}\`,`,
    `  commit \`${json.commit}\`, generated in run ${json.run_url}).`,
    '',
  );

  // --- Gates --------------------------------------------------------------
  out.push('## Gates', '', '| gate | threshold | measured | verdict |', '|---|---|---|---|');
  if (budget !== null) {
    out.push(
      `| first load (index.html + entry JS/CSS + core-wasm + sqlite3.wasm, gzip -9) ` +
        `| < ${fmt(budget.limit)} bytes | ${fmt(budget.measured)} bytes | ${budget.verdict} |`,
    );
  }
  if (wasmLimit > 0) {
    out.push(
      `| import-wasm (epiora_import_wasm_bg.wasm, gzip -9) | ≤ ${fmt(wasmLimit)} bytes ` +
        `| ${fmt(summary.importWasmBytes)} bytes | ${summary.importWasmBytes <= wasmLimit ? 'PASS' : 'FAIL'} |`,
    );
  }
  if (eng.wasmBytes !== null && eng.wasmBudget !== null) {
    out.push(
      `| engine wasm (epiora_wasm_bg.wasm, gzip -9) | ≤ ${fmt(eng.wasmBudget)} bytes ` +
        `| ${fmt(eng.wasmBytes)} bytes | ${eng.wasmBytes <= eng.wasmBudget ? 'PASS' : 'FAIL'} |`,
    );
  }
  for (const name of ['import_1m', 'open_tables_1m', 'means_1m']) {
    const g = gateOf(name);
    if (g === undefined) continue;
    out.push(
      `| \`${name}\` median, persistent profile (${g.ok} ok / ${g.failed} failed / ${g.skipped} skipped) ` +
        `| ≤ ${fmt(g.thresholdMs)} ms | ${fmt(g.medianMs)} ms | ${g.verdict} |`,
    );
  }
  out.push(
    '',
    '`import_1m` and `open_tables_1m` thresholds are the owner-picked v0.3 Task 17 numbers',
    '([PR #52](https://github.com/dorrabbkhan/Epiora/pull/52#issuecomment-6807191386)); `means_1m` is',
    'the owner-picked v1.0 Task 19 number ([PR #94](https://github.com/dorrabbkhan/Epiora/pull/94) —',
    'the Task 18 measurement’s slowest-attempt p90 × 1.25). A perf scenario passes when the median',
    '`ms` of its successful samples is ≤ the threshold. The import-wasm measured size is read from',
    'the perf run’s `summary.md`; the engine wasm size from the `engine` run’s `v0.2-validation-md`',
    'header (`EPIORA_WASM_GZIP_BYTES`, the `engine` job’s measured `gzip -9` output).',
    '',
  );
  if (eng.benchMs !== null && eng.benchBudget !== null) {
    out.push(
      `Chromium bench median (1,000,000 rows, \`datasetFromColumns\` + stratified \`tables\`):`,
      `**${fmt(eng.benchMs)} ms** (budget < ${fmt(eng.benchBudget)} ms — from the \`engine\` run’s`,
      '`v0.2-validation-md` header, `EPIORA_BENCH_MEDIAN_MS`).',
      '',
    );
  }

  // --- Perf -----------------------------------------------------------------
  out.push(
    `## Performance — ${source.workflow} run attempt ${source.attempt}`,
    '',
    `profile(s): ${summary.profiles.join(', ')}`,
    '',
    '| scenario | ok | failed | skipped | field | median | p90 |',
    '|---|---|---|---|---|---|---|',
  );
  for (const s of summary.scenarios) {
    out.push(
      `| ${s.scenario} | ${s.ok} | ${s.failed} | ${s.skipped} | ${s.field} | ${cell(s.median)} | ${cell(s.p90)} |`,
    );
  }
  if (summary.failures.length > 0) {
    out.push('', 'Failed samples (a failure is a measurement, never hidden):', '');
    for (const f of summary.failures) {
      out.push(`- run ${f.run} · \`${f.scenario}\` · ${f.error}`);
    }
  }
  if (input.earlierAttempts.length > 0) {
    out.push(
      '',
      `### Earlier attempts of run ${source.id} (read from each attempt’s \`perf\` job log)`,
      '',
    );
    for (const a of input.earlierAttempts) {
      const f = parseAttemptFacts(a.perfJobLog);
      const bits = [];
      for (const e of f.gateErrors) bits.push(`the owner-gates test failed: \`${e}\``);
      for (const [name, s] of [...f.medians.entries()].sort()) {
        const g = gateOf(name);
        const cmp = g === undefined ? '' : s.median <= g.thresholdMs ? ' ≤ ' : ' > ';
        bits.push(
          `\`${name}\` median ${fmt(s.median)} ms` +
            (g === undefined ? '' : `${cmp}threshold ${fmt(g.thresholdMs)} ms`),
        );
      }
      out.push(
        `- **Attempt ${a.attempt}** — \`perf\` job conclusion **${a.conclusion}**` +
          (bits.length === 0 ? '.' : ` — ${bits.join('; ')}.`),
      );
    }
  }

  // --- D7 ---------------------------------------------------------------------
  const d7 = summary.scenarios.filter((s) => s.field === 'ms' && /_cpu\d+$/.test(s.scenario));
  out.push('', '## D7 report (Chromium CPU throttling ×4 — reported, not gated)', '');
  out.push('| scenario | ok | failed | median ms | p90 ms |', '|---|---|---|---|---|');
  for (const s of d7) {
    out.push(`| ${s.scenario} | ${s.ok} | ${s.failed} | ${cell(s.median)} | ${cell(s.p90)} |`);
  }

  // --- Corpus coverage ---------------------------------------------------------
  out.push(
    '',
    '## Corpus coverage',
    '',
    `One row per \`validation::REGISTRY\` statistic (${fmt(json.statistics.length)} total), read` +
      ' from the `engine` run’s',
    '`v1.0-validation-json` artifact — the same `build_rows` measurements the Markdown report',
    'prints. *Worst relative error* is the maximum `|actual − expected| / |expected|` over every',
    'leaf of the covering fixtures (`|actual|` when the reference is 0); `inf` marks a leaf the',
    'engine did not produce in the reference’s kind (number vs undefined). A row passes iff its',
    'worst error is within the class tolerance (`closed_form` 1e-9, `iterative` 1e-6).',
    '',
    '| Statistic | Method | Class | References | Cases | Worst relative error |',
    '|---|---|---|---|---|---|---|',
  );
  for (const s of json.statistics) {
    const refs = Object.values(s.references ?? {});
    out.push(
      `| ${s.id} | ${s.method} | ${s.class} | ${refs.length === 0 ? '—' : refs.join('; ')} ` +
        `| ${s.cases} | ${fmtWorst(s)} |`,
    );
  }

  // --- Reference checks ------------------------------------------------------------
  out.push(
    '',
    '## Reference checks (display tolerance)',
    '',
    '| check | mapped values | mismatches | tolerance |',
    '|---|---|---|---|',
  );
  if (eng.ei7 !== null) {
    out.push(
      `| Epi Info 7 (${eng.ei7.version}, \`ei7/oswego.json\`) | ${eng.ei7.mapped} ` +
        `| ${eng.ei7.mismatches} | \`ei7_display\` |`,
    );
  }
  if (eng.openepi !== null) {
    out.push(
      `| OpenEpi (\`openepi/*.json\`, ${fmt(eng.openepi.calculators)} calculators) ` +
        `| ${eng.openepi.mapped} | ${eng.openepi.mismatches} | \`openepi_display\` |`,
    );
  }
  out.push(
    '',
    'Read from the `## Epi Info 7 check` and `## OpenEpi check` sections of the `engine` run’s',
    '`v0.2-validation-md` artifact; `ei7_display` and `openepi_display` are half a unit in the last',
    `displayed decimal.${eng.openepi === null ? '' : ` OpenEpi also records ${eng.openepi.differences} documented method difference(s) (docs/decisions.md \`### v1.0 Task 13 — method choices\`).`}`,
    '',
  );

  // --- R export ----------------------------------------------------------------------
  out.push(`## R export (r-export run ${input.rExportRun.url}, conclusion ${input.rExportRun.conclusion})`, '');
  out.push(
    `- Exported scripts run under the pinned renv: **${rexport.scripts ?? 'not run'}**.`,
    `- Statistic leaves compared to their fixture values (E7 tolerances): ` +
      `**${rexport.checked === null ? 'not compared' : fmt(rexport.checked)}**, mismatches: **${fmt(rexport.mismatches)}**.`,
    '',
  );

  // --- Stata ------------------------------------------------------------------------------
  out.push('## Stata export', '');
  out.push(
    input.stata === 'verified'
      ? 'Verified against the owner’s local Stata (`fixtures/stata/results.json`).'
      : input.stata === 'deferred'
        ? '**Deferred** — the owner has no Stata licence (v1.0 Task 20, `docs/decisions.md` ' +
          '`### v1.0 Task 20 — Stata export deferred`); carried forward as an open decision.'
        : 'Not verified for v1.0: `docs/decisions.md` records neither the Task 20 deferral ' +
          'nor verified results.',
    '',
  );

  // --- Explain ------------------------------------------------------------------------------
  out.push('## Explain coverage', '');
  out.push(
    `- Engine: \`every_registry_statistic_explains\` (\`crates/epiora-core/tests/explain.rs\`) — ` +
      `all ${fmt(json.statistics.length)} registry statistics explain; green in the \`engine\` ` +
      `run (${input.engineRun.url}, conclusion ${input.engineRun.conclusion}).`,
    '- App: `every_engine_formula_has_a_template` and the formula guard ' +
      '(`app/src/explain/coverage.test.ts`, `guard.test.ts`) — every engine formula has a ' +
      `template whose numbers come only from the trace; green in the \`app\` run ` +
      `(${source.url}, conclusion ${source.conclusion}).`,
    '',
  );

  // --- axe --------------------------------------------------------------------------------------
  out.push(
    '## Accessibility — axe (e2e/a11y.spec.ts)',
    '',
    '| engine | routes | themes | scans | violations |',
    '|---|---|---|---|---|',
  );
  for (const [engine, a] of [...axe.entries()].sort()) {
    out.push(`| ${engine} | ${a.routes.size} | ${a.themes.size} | ${a.scans} | 0 |`);
  }
  if (e2ePassed !== null) {
    out.push('', `Playwright end-to-end total: **${fmt(e2ePassed)} tests passed** across the three engines.`);
  }

  // --- Sizes -------------------------------------------------------------------------------------
  out.push('', '## Sizes (gzip -9, bytes)', '', '| file | bytes |', '|---|---|');
  for (const f of summary.files) {
    out.push(`| ${f.rel} | ${fmt(f.bytes)} |`);
  }
  if (summary.firstLoadTotal !== null) {
    out.push(`| **first-load total** | **${fmt(summary.firstLoadTotal)}** |`);
  }
  out.push(
    '',
    `import-wasm gzip -9: **${fmt(summary.importWasmBytes)} bytes**`,
    '(`crates/epiora-import-wasm/pkg/epiora_import_wasm_bg.wasm`).',
    '',
  );

  // --- Sign-off ------------------------------------------------------------------------------------
  out.push('## Sign-off', '');
  out.push(
    '- Epidemiologist adviser sign-off: **pending** (G5 — the owner looks for an adviser ' +
      'separately; v1.0 ships as a pre-release, platform §12.9).',
    '- Explain-text review: **pending** (G5 — the explain texts are marked “pending adviser ' +
      'review”).',
    '',
  );
  return `${out.join('\n')}\n`;
}
