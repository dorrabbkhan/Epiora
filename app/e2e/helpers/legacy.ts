interface DbExport {
  sqlite3_js_db_export(db: unknown, schema: string): Uint8Array;
}

let sqlite3Promise: Promise<Sqlite3Static> | null = null;

function getSqlite(): Promise<Sqlite3Static> {
  sqlite3Promise ??= sqlite3InitModule() as Promise<Sqlite3Static>;
  return sqlite3Promise;
}

async function makePlainBinaryDb(): Promise<Buffer> {
  const sqlite3 = await getSqlite();
  const db = new sqlite3.oo1.DB(':memory:');
  try {
    db.exec('CREATE TABLE measurements (id INTEGER, payload BLOB, note TEXT)');
    db.exec("INSERT INTO measurements VALUES (1, x'0102', 'first'), (2, x'0304', 'second')");
    return Buffer.from((sqlite3.capi as unknown as DbExport).sqlite3_js_db_export(db, 'main'));
  } finally {
    db.close();
  }
}

/** Selects an in-memory sqlite database with one BLOB column. Keeping
 *  the generated bytes out of `fixtures/` preserves the fixture oracle
 *  rule while exercising the real legacy plain-table decoder. */
export async function choosePlainBinaryDb(page: Page): Promise<void> {
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Choose project files' }).click();
  await (await chooser).setFiles({
    name: 'binary.db',
    mimeType: 'application/octet-stream',
    buffer: await makePlainBinaryDb(),
  });
}

export async function chooseFiles(page: Page, paths: string[]): Promise<void> {
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Choose project files' }).click();
  await (await chooser).setFiles(paths);
}

export async function walkToPreview(page: Page, paths = [SAMPLE_PRJ, SAMPLE_DB]): Promise<void> {
  await page.goto('/legacy');
  await chooseFiles(page, paths);
  await expect(page.getByRole('heading', { name: /Preview SQLiteSample2/ })).toBeVisible();
}

export async function importSample(page: Page): Promise<string> {
  await walkToPreview(page);
  await page.getByRole('button', { name: 'Confirm import' }).click();
  await expect(page).toHaveURL(/\/p\/[^/]+$/, { timeout: 60_000 });
  await expect(page.getByRole('heading', { name: 'SQLiteSample2' })).toBeVisible();
  return page.url().split('/p/')[1]!;
}

export async function chooseReimportFile(page: Page, path: string): Promise<void> {
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Choose newer copy' }).click();
  await (await chooser).setFiles(path);
}
