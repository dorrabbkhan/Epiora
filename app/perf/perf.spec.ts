// Perf spec (v0.3 plan Tasks 16–17, spec §10.3) — Chromium only,
// production build. Task 16 measured; Task 17 gates: the file's last
// test enforces the owner-picked thresholds in GATES below (PR #52) —
// a scenario passes when the median `ms` of its successful samples is
// ≤ the threshold. Every other scenario is reported, never gated.
//
// Each `test()` is one sample in a fresh browser context, hence a
// fresh OPFS store. Every scenario appends one JSON object per line to
// PERF_OUT; perf/summarise.mjs turns the lines into median/p90 per
// scenario plus the gzip -9 sizes.
//
// Run with EPIORA_PERF=1 (playwright.config.ts switches testDir to
// ./perf). Environment: PERF_RUNS samples (5 on push to main; CI
// passes the workflow_dispatch `runs` input, default 10), PERF_ROWS
// rows for the big CSV (default 1,000,000; 100,000 for a local sanity
// run — gates only evaluate the `1m` names), PERF_PROFILE =
// `persistent` (each sample's page lives in a fresh on-disk user-data
// dir, deleted after the sample — a real user's profile; the only
// profile CI uses, per the owner's PR #52 decision) or `ephemeral`
// (the off-the-record context Playwright's `page` fixture would give —
// kept for local diagnosis only), PERF_CPU_THROTTLE runs the D7
// report: both gated scenarios under Chromium CPU throttling
// (Emulation.setCPUThrottlingRate), recorded as `*_cpu<N>` scenarios —
// reported, not gated. PERF_CSV / PERF_CSV_10K / PERF_OUT override
// paths. Missing CSVs are generated by perf/gen-csv.mjs — same seed,
// same bytes.
//
// The spec launches Chromium itself in both modes rather than using
// the managed `page` fixture: the launch args carry
// --enable-precise-memory-info so the scroll pass's
// performance.memory heap readings are exact bytes, not Chromium's
// quantised figures (a flat 286,000,000 on the first run). Every
// recorded line carries `profile` so a results.jsonl from either
// mode is self-describing.

