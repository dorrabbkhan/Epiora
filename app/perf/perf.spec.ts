// Perf spec (v0.3 plan Tasks 16–17, spec §10.3; v1.0 plan Tasks
// 18–19) — Chromium only, production build. Task 16 measured; Task 17
// gates: the file's last test enforces the owner-picked thresholds in
// gate-eval.ts's GATES (PR #52; means_1m added by Task 19 with the
// owner's PR #94 pick) — a scenario passes when the median `ms` of
// its successful samples is ≤ the threshold. Every other scenario is
// reported, never gated.
//
// PERF_SCENARIOS (the `scenarios` dispatch input, owner instruction
// 2026-11-19) restricts which scenarios a sample runs — push to main
// always runs everything. See shared.ts's scenarioEnabled.
//
// Each `test()` is one sample in a fresh browser context, hence a
// fresh OPFS store. Every scenario appends one JSON object per line to
// PERF_OUT; perf/summarise.mjs turns the lines into median/p90 per
// scenario plus the gzip -9 sizes.
//
// The scenario bodies live in perf/scenarios/*.ts (v1.0 Task 18 split
// — the single file had grown past the ~400-line rule; behaviour is
// unchanged). One sample runs, in order: empty_store_opfs,
// create_project, import_1m, reimport_1m, open_tables_1m, means_1m,
// grid_scroll_10k, grid_scroll_1m — each dependent records its own
// skip when the scenario it needs failed.
//
// Run with EPIORA_PERF=1 (playwright.config.ts switches testDir to
// ./perf). Environment: PERF_RUNS samples (5 on push to main; CI
// passes the workflow_dispatch `runs` input, default 10), PERF_ROWS
// rows for the big CSV (default 1,000,000; 100,000 for a local sanity
// run — gates only evaluate the `1m` names), PERF_PROFILE =
// `persistent` (each sample's page lives in a fresh on-disk user-data
// dir, deleted after the sample — a real user's profile; the only
// profile CI uses, per the owner's PR #52 decision) or `ephemeral`
// (the off-the-record context Playwright's `page` fixture would give —
// kept for local diagnosis only), PERF_CPU_THROTTLE runs the D7
// report: both gated scenarios under Chromium CPU throttling
// (Emulation.setCPUThrottlingRate), recorded as `*_cpu<N>` scenarios —
// reported, not gated. PERF_CSV / PERF_CSV_10K / PERF_OUT override
// paths. Missing CSVs are generated by perf/gen-csv.mjs — same seed,
// same bytes.
//
// The spec launches Chromium itself in both modes rather than using
// the managed `page` fixture: the launch args carry
// --enable-precise-memory-info so the scroll pass's
// performance.memory heap readings are exact bytes, not Chromium's
// quantised figures (a flat 286,000,000 on the first run). Every
// recorded line carries `profile` so a results.jsonl from either
// mode is self-describing.

import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  chromium,
  expect,
  test as base,
  type BrowserContext,
  type BrowserContextOptions,
  type Page,
} from '@playwright/test';
import { evaluateGates, type PerfLine } from './gate-eval';
import {
  BATCH,
  BIG_CSV,
  CPU_THROTTLE,
  ensureCsv,
  ensureEditedCsv,
  GATES_MD,
  label,
  OUT,
  PROFILE,
  routeCsv,
  ROWS,
  RUNS,
  SCENARIOS_FILTERED,
  SMALL_CSV,
} from './scenarios/shared';
import type { SampleCtx } from './scenarios/shared';
import { runStore } from './scenarios/store';
import { runImport } from './scenarios/import';
import { runTables } from './scenarios/tables';
import { runMeans } from './scenarios/means';
import { runGrid } from './scenarios/grid';

/** One sample's page. `persistent` launches a persistent context on a
 *  fresh temp user-data dir (a real user's on-disk profile — the
 *  control for the off-the-record OPFS ceiling diagnosis) and deletes
 *  the dir at teardown; `ephemeral` matches what the managed `page`
 *  fixture gave the first run: `chromium.launch` + `newContext` on the
 *  project's `use` options. Both carry --enable-precise-memory-info so
 *  heapStartBytes/heapEndBytes are exact. */
const test = base.extend<{ perfPage: Page }>({
  perfPage: async ({}, use, testInfo) => {
    const u = testInfo.project.use;
    const contextOptions: BrowserContextOptions = {};
    if (u.baseURL !== undefined) contextOptions.baseURL = u.baseURL;
    if (u.viewport !== undefined) contextOptions.viewport = u.viewport;
    if (u.deviceScaleFactor !== undefined)
      contextOptions.deviceScaleFactor = u.deviceScaleFactor;
    if (u.isMobile !== undefined) contextOptions.isMobile = u.isMobile;
    if (u.hasTouch !== undefined) contextOptions.hasTouch = u.hasTouch;
    if (u.userAgent !== undefined) contextOptions.userAgent = u.userAgent;
    const args = ['--enable-precise-memory-info'];
    let context: BrowserContext;
    let userDataDir: string | null = null;
    let close: () => Promise<unknown>;
    if (PROFILE === 'persistent') {
      userDataDir = mkdtempSync(join(tmpdir(), 'epiora-perf-profile-'));
      context = await chromium.launchPersistentContext(userDataDir, {
        ...contextOptions,
        args,
      });
      close = () => context.close();
    } else {
      const browser = await chromium.launch({ args });
      context = await browser.newContext(contextOptions);
      close = () => browser.close();
    }
    const page = context.pages()[0] ?? (await context.newPage());
    if (CPU_THROTTLE > 1) {
      // D7 report: throttle before anything runs in the page.
      const cdp = await context.newCDPSession(page);
      await cdp.send('Emulation.setCPUThrottlingRate', { rate: CPU_THROTTLE });
    }
    await use(page);
    await close();
    if (userDataDir !== null) {
      rmSync(userDataDir, { recursive: true, force: true });
    }
  },
});

// No `serial` mode: one failed sample must not skip the rest — the
// run's whole point is a distribution, and a failure is a measurement.
// `--workers=1` keeps the samples in order.
test.describe.configure({ retries: 0 });

for (let i = 0; i < RUNS; i++) {
  test(`sample ${i + 1}/${RUNS} (${label}, ${PROFILE} profile)`, async ({ perfPage: page }) => {
    test.setTimeout(30 * 60_000);
    ensureCsv(BIG_CSV, ROWS);
    ensureEditedCsv();
    ensureCsv(SMALL_CSV, 10_000);
    await routeCsv(page);

    // The worker's console (sahpool's `storeErr` console.errors the
    // DOMException a failed OPFS op threw) is the only place the
    // underlying error name survives the RPC mapping — keep a tail.
    const consoleLines: string[] = [];
    page.on('console', (msg) => {
      const text = msg.text();
      if (/^perf-scroll-steps? \d+$/.test(text)) return;
      consoleLines.push(`${msg.type()}: ${text}`);
      if (consoleLines.length > 60) consoleLines.shift();
    });
    page.on('pageerror', (e) => consoleLines.push(`pageerror: ${e.message}`));

    const ctx: SampleCtx = {
      page,
      run: i + 1,
      consoleLines,
      // OPFS growth samples taken while the big commits run; consumed
      // by failureDiagnostics (and cleared) on the first failure.
      growthLog: [],
      projectId: '',
      datasetId: null,
      gatedOnly: CPU_THROTTLE > 1,
    };

    await page.goto('/');
    await runStore(ctx);
    await runImport(ctx);
    await runTables(ctx);
    await runMeans(ctx);
    await runGrid(ctx);
  });
}

// --- Owner gates (v0.3 Task 17) --------------------------------------
//
// Thresholds, medians and the batch id live in ./gate-eval.ts so the
// node:test lane (app/scripts/perf-gate.test.mjs) exercises the real
// gate code; this test is the IO + verdict only.
test('owner gates: medians meet the PR #52 thresholds', async () => {
  // The throttled (D7) pass records `*_cpu<N>` names and never gates;
  // pass 1's gates.md stays the report.
  if (CPU_THROTTLE > 1) return;

  const lines: PerfLine[] = existsSync(OUT)
    ? readFileSync(OUT, 'utf8')
        .split('\n')
        .filter((l) => l.trim() !== '')
        .map((l) => JSON.parse(l) as PerfLine)
    : [];
  const { markdown, failures } = evaluateGates(lines, {
    batch: BATCH,
    profile: PROFILE,
    label,
    filtered: SCENARIOS_FILTERED,
  });
  writeFileSync(GATES_MD, markdown);
  expect(failures, failures.join('; ')).toEqual([]);
});
