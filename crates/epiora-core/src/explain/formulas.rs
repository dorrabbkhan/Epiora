//! `formulas` — every formula id a trace can emit (v1.0 Task 10,
//! spec §6). The app's explain templates are keyed by these ids;
//! `coverage.test.ts` (Task 16) asserts `FORMULAS` ⊆ template ids
//! with no orphans, and `guard.test.ts` substitutes a step's
//! `values` into the template and requires it to reproduce
//! `step.result` within the statistic's tolerance class.
//!
//! `method.*` ids are the `ExplainKind::Method` steps — their
//! `values` are the method's inputs and the `result` only; the app
//! describes the method in words and does not evaluate them.
//!
//! `data` is the identity for directly tabulated values (counts,
//! order statistics, indices): `values = {value}` computes
//! `value`.

