//! Canonical JSON (spec §4.3): our own writer, not serde_json's —
//! object keys sorted by byte order, no whitespace, RFC 8259 minimal
//! string escaping (`\u00xx` lowercase), integers as decimal, f64 via
//! `ryu::Buffer::format_finite`. A crate enabling serde_json's
//! `preserve_order` cannot change it.

use serde_json::Value;

/// The canonical JSON of `v`.
pub fn canonical_json(v: &Value) -> String {
    let mut out = String::new();
    write_value(v, &mut out);
    out
}

fn write_value(v: &Value, out: &mut String) {
    match v {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                out.push_str(&i.to_string());
            } else if let Some(u) = n.as_u64() {
                out.push_str(&u.to_string());
            } else if let Some(f) = n.as_f64() {
                // serde_json::Number is always finite.
                out.push_str(ryu::Buffer::new().format_finite(f));
            }
        }
        Value::String(s) => write_string(s, out),
        Value::Array(items) => {
            out.push('[');
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_value(item, out);
            }
            out.push(']');
        }
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            out.push('{');
            for (i, key) in keys.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_string(key, out);
                out.push(':');
                if let Some(child) = map.get(*key) {
                    write_value(child, out);
                }
            }
            out.push('}');
        }
    }
}

/// RFC 8259 minimal escaping: `"` and `\` use shorthand, other control
/// characters become `\u00xx` (lowercase hex), everything else is
/// verbatim UTF-8.
fn write_string(s: &str, out: &mut String) {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => {
                let b = c as u32;
                out.push_str("\\u00");
                out.push(HEX[(b >> 4) as usize] as char);
                out.push(HEX[(b & 0xf) as usize] as char);
            }
            c => out.push(c),
        }
    }
    out.push('"');
}
