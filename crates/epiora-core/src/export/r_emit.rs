//! `r_emit` — the parts of a generated `analysis.R` that are not
//! verbatim fixtures: the provenance header, the `epi_walk` printer,
//! the shims that turn `write_fixture`/`calc_write` calls into
//! `EPIORA` lines, the CSV reader prelude, the DATASETS env emitter
//! and the cross-tab helpers. All emitted R is ASCII-safe; `∅`
//! markers and non-ASCII names go through `\u{…}` escapes.

use crate::dataset::{ColumnData, Dataset};
use serde_json::{Map, Value};

/// `x` as an R numeric literal.
pub fn lit_num(x: f64) -> String {
    if x.is_nan() {
        "NA_real_".into()
    } else if x == f64::INFINITY {
        "Inf".into()
    } else if x == f64::NEG_INFINITY {
        "-Inf".into()
    } else if x.fract() == 0.0 && x.abs() < 1e15 {
        format!("{x:.0}")
    } else {
        ryu::Buffer::new().format_finite(x).to_string()
    }
}

/// A string as a double-quoted R literal, escaping non-ASCII to
/// `\u{XXXX}` so the script stays ASCII on every filesystem.
pub fn lit_str(s: &str) -> String {
    let mut out = String::from('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_ascii() => out.push(c),
            c => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
        }
    }
    out.push('"');
    out
}

/// A JSON value as an R literal.
pub fn lit_json(v: &Value) -> String {
    match v {
        Value::Null => "NULL".into(),
        Value::Bool(b) => if *b { "TRUE" } else { "FALSE" }.into(),
        Value::Number(n) => match n.as_f64() {
            Some(x) => lit_num(x),
            None => n.to_string(),
        },
        Value::String(s) => lit_str(s),
        Value::Array(a) => format!(
            "list({})",
            a.iter().map(lit_json).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(m) => lit_named(m),
    }
}

/// A JSON object as `list("a" = …, "b" = …)`.
pub fn lit_named(m: &Map<String, Value>) -> String {
    let mut pairs: Vec<String> = m
        .iter()
        .map(|(k, v)| format!("{} = {}", lit_str(k), lit_json(v)))
        .collect();
    pairs.sort();
    format!("list({})", pairs.join(", "))
}

/// A JSON array of rows as `matrix(c(…), nrow, byrow = TRUE)`.
pub fn lit_matrix(rows: &Value) -> String {
    let cells: Vec<String> = rows
        .as_array()
        .map(|rs| {
            rs.iter()
                .flat_map(|r| {
                    r.as_array()
                        .map(|c| c.iter().collect::<Vec<_>>())
                        .unwrap_or_default()
                })
                .map(lit_json)
                .collect()
        })
        .unwrap_or_default();
    let nrow = rows.as_array().map(Vec::len).unwrap_or(0);
    format!(
        "matrix(c({}), nrow = {}, byrow = TRUE)",
        cells.join(", "),
        nrow
    )
}

/// A JSON array of tables as `list(matrix(…), …)`.
pub fn lit_tables(strata: &Value) -> String {
    let items: Vec<String> = strata
        .as_array()
        .map(|ss| ss.iter().map(lit_matrix).collect())
        .unwrap_or_default();
    format!("list({})", items.join(", "))
}

/// The header the spec §8.1 fixes: receipt hash, engine version, R
/// packages the script calls, licence line.
pub fn header(title: &str, packages: &[&str], receipt_sha256: &str) -> String {
    format!(
        "# {title} — generated by epiora-core {ver}\n\
         # Do not edit; regenerate with epiora.\n\
         # R code: MIT licence\n\
         # receipt_sha256: {sha}\n\
         # engine: {ver}\n\
         # R packages: {pkgs}\n\n",
        title = title,
        ver = env!("CARGO_PKG_VERSION"),
        sha = receipt_sha256,
        pkgs = packages.join(", ")
    )
}

/// The printer + shims every script prepends. `epi_walk` flattens a
/// generator `expected` tree to `EPIORA <path> <value>` lines: a leaf
/// is the list whose names (sans `r_default`) are `class`+`value`,
/// matching `corpus::compare`'s leaf detection; `value: null`/NA
/// prints `NULL`; array paths print `[i]` 0-based. `write_fixture`
/// and `calc_write` keep their generator signatures so the verbatim
/// `*_write` drivers call them unchanged — here they walk instead of
/// writing fixture JSON. `osw_table` exists only because
/// `twobytwo_write`'s all-zero branch references it; the value it
/// returns is `nullify`d before use, so any valid 2×2 does.
pub const PRELUDE: &str = r#"epi_walk <- function(x, prefix = "") {
  is_leaf <- is.list(x) && !is.null(names(x)) &&
    identical(sort(names(x)[names(x) != "r_default"]), c("class", "value"))
  if (is_leaf) {
    v <- x$value
    if (is.null(v) || length(v) == 0 || (length(v) == 1 && is.na(v))) {
      cat(sprintf("EPIORA %s NULL\n", prefix))
    } else {
      cat(sprintf("EPIORA %s %.17g\n", prefix, as.numeric(v)))
    }
    return(invisible(NULL))
  }
  if (is.list(x)) {
    nms <- names(x)
    for (i in seq_along(x)) {
      nm <- if (!is.null(nms) && !is.na(nms[i]) && nzchar(nms[i])) {
        if (prefix == "") nms[i] else paste0(".", nms[i])
      } else {
        sprintf("[%d]", i - 1L)
      }
      epi_walk(x[[i]], paste0(prefix, nm))
    }
    return(invisible(NULL))
  }
}
write_fixture <- function(dir, id, procedure, inputs, expected, ...) {
  epi_walk(expected, "")
}
calc_write <- function(dir, id, inputs, expected, ...) {
  epi_walk(expected, "")
}
pkg_versions <- function(pkgs = NULL) list()
write_dataset <- function(id, columns) invisible(NULL)
osw_table <- function(food) {
  matrix(c(43L, 11L, 3L, 18L), nrow = 2, byrow = TRUE)
}
"#;

/// `suppressPackageStartupMessages(library(epitools))` — the corpus
/// R calls `riskratio`/`oddsratio`/… unqualified because
/// `generate.R` attached epitools. Scripts whose verbatim text makes
/// those bare calls get this line and `epitools` in the package
/// header.
pub const ATTACH_EPITOOLS: &str = "suppressPackageStartupMessages(library(epitools))\n";

/// `true` when `script` calls an epitools function without a `pkg::`
/// qualifier (word/`.`/`:` before the name means qualified).
pub fn needs_epitools(script: &str) -> bool {
    const CALLS: &[&str] = &[
        "riskratio(",
        "riskratio.small(",
        "oddsratio(",
        "oddsratio.small(",
        "tab2by2.test(",
    ];
    let bytes = script.as_bytes();
    for pat in CALLS {
        let mut start = 0;
        while let Some(off) = script[start..].find(pat) {
            let i = start + off;
            let bare = i == 0
                || !(bytes[i - 1].is_ascii_alphanumeric()
                    || bytes[i - 1] == b'_'
                    || bytes[i - 1] == b'.'
                    || bytes[i - 1] == b':');
            if bare {
                return true;
            }
            start = i + pat.len();
        }
    }
    false
}

/// The CSV reader prelude — emitted only for dataset-backed
/// scripts. The typed `*_col` readers turn the marker text back into
/// `NA` and coerce; `read.csv` is told `na.strings = character(0)`
/// so literal `"NA"` text and empty strings survive, and every
/// column arrives as character for the marker pass.
pub const READER_PRELUDE: &str = r#"epi_na <- function(x, marker) { x[x == marker] <- NA; x }
epi_num <- function(raw, col, marker) as.numeric(epi_na(raw[[col]], marker))
epi_int <- function(raw, col, marker) as.integer(epi_na(raw[[col]], marker))
epi_txt <- function(raw, col, marker) epi_na(as.character(raw[[col]]), marker)
epi_bool <- function(raw, col, marker) epi_na(raw[[col]], marker) == "TRUE"
epi_date <- function(raw, col, marker) as.Date(epi_na(raw[[col]], marker))
raw <- read.csv("data.csv", stringsAsFactors = FALSE, check.names = FALSE,
                colClasses = "character", encoding = "UTF-8",
                na.strings = character(0))
"#;

/// `raw <- read.csv(…)`, helpers, and the `stopifnot(nrow)` check.
pub fn reader(n: usize) -> String {
    format!("{READER_PRELUDE}stopifnot(nrow(raw) == {n})\n\n")
}

/// The cross-tab helpers for procedure scripts. `epi_cats` mirrors
/// `tabulate::categories` ordering in R (Boolean Yes first, others
/// sorted); `epi_orient` mirrors the 2×2 `{0,1}`→`{1,0}` flip. The
/// caller passes the resolved level vectors, so these stay small.
pub const XTAB_PRELUDE: &str = r#"epi_cell <- function(e, o, ev, ov) {
  es <- if (is.na(ev)) is.na(e) else (!is.na(e) & e == ev)
  os <- if (is.na(ov)) is.na(o) else (!is.na(o) & o == ov)
  sum(es & os)
}
epi_xtab <- function(e, o, el, ol) {
  matrix(c(epi_cell(e, o, el[1], ol[1]), epi_cell(e, o, el[1], ol[2]),
           epi_cell(e, o, el[2], ol[1]), epi_cell(e, o, el[2], ol[2])),
         nrow = 2, byrow = TRUE)
}
epi_strata <- function(sv, slv, e, o, el, ol) {
  g <- expand.grid(lapply(rev(slv), seq_along))
  g <- g[rev(seq_along(g))]
  out <- lapply(seq_len(nrow(g)), function(i) {
    sel <- rep(TRUE, length(e))
    for (v in seq_along(sv)) {
      lv <- slv[[v]][g[i, v]]
      sel <- sel & if (is.na(lv)) is.na(sv[[v]])
                   else (!is.na(sv[[v]]) & sv[[v]] == lv)
    }
    epi_xtab(e[sel], o[sel], el, ol)
  })
  out
}
"#;

/// The reader function name for a column's storage type — mirrors
/// the `type` tags `fixtures/R/data.R` writes into dataset JSON.
pub fn col_reader(d: &ColumnData) -> &'static str {
    match d {
        ColumnData::Integer(_) => "epi_int",
        ColumnData::Real(_) => "epi_num",
        ColumnData::Text(_) => "epi_txt",
        ColumnData::Boolean(_) => "epi_bool",
        ColumnData::Date(_) => "epi_date",
        // Cells carry raw seconds: `epi_int` for Time (≤ 86_399),
        // `epi_num` for DateTime — its seconds overflow `as.integer`
        // past 2038 (v1.1 spec §4.3).
        ColumnData::Time(_) => "epi_int",
        ColumnData::DateTime(_) => "epi_num",
    }
}

fn col_type(d: &ColumnData) -> &'static str {
    match d {
        ColumnData::Integer(_) => "integer",
        ColumnData::Real(_) => "real",
        ColumnData::Text(_) => "text",
        ColumnData::Boolean(_) => "boolean",
        ColumnData::Date(_) => "date",
        ColumnData::Time(_) => "integer",
        ColumnData::DateTime(_) => "real",
    }
}

/// Emits the `DATASETS` env `freq_write`/`means_write` read through
/// `get(dataset, envir = DATASETS)`. `cols` is either every column or
/// the subset a procedure touches; a Boolean group/stratify column is
/// emitted as a `Yes`/`No` factor so `sort(unique(x))` inside the
/// verbatim R keeps the engine's Yes-first order.
pub fn datasets_env(
    out: &mut String,
    ds_id: &str,
    ds: &Dataset,
    markers: &[String],
    cols: &[(&str, bool)],
) -> Result<(), crate::EngineError> {
    out.push_str("DATASETS <- new.env(parent = emptyenv())\n");
    let items: Vec<String> = cols
        .iter()
        .map(|(name, bool_factor)| {
            let c = ds.column(name)?;
            let idx = ds
                .columns()
                .iter()
                .position(|x| x.name == *name)
                .ok_or_else(|| crate::EngineError::UnknownVariable {
                    name: (*name).to_string(),
                })?;
            let reader = col_reader(&c.data);
            let marker = lit_str(&markers[idx]);
            let values = if *bool_factor {
                format!(
                    "factor(ifelse({r}(raw, {n}, {m}), \"Yes\", \"No\"), levels = c(\"Yes\", \"No\"))",
                    r = reader,
                    n = lit_str(name),
                    m = marker
                )
            } else {
                format!("{}(raw, {}, {})", reader, lit_str(name), marker)
            };
            Ok(format!(
                "  {} = list(type = {}, values = {})",
                name,
                lit_str(col_type(&c.data)),
                values
            ))
        })
        .collect::<Result<Vec<String>, crate::EngineError>>()?;
    out.push_str(&format!(
        "assign({}, list(\n{}\n), envir = DATASETS)\n\n",
        lit_str(ds_id),
        items.join(",\n")
    ));
    Ok(())
}
