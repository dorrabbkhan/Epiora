#![cfg(feature = "corpus")]

use epiora_core::corpus::report::{build_report, build_report_json, build_rows};
use epiora_core::validation::REGISTRY;
use std::path::{Path, PathBuf};

fn fixtures_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../fixtures")
}

/// Whether any covering fixture recorded an `r_version` or a package
/// — the same signal the report's `has_r_reference` collects. The
/// seeded `random_numbers` golden carries no `source` at all, so its
/// registry entry is the one row with no R reference (the plan's
/// `"r"?` is optional).
fn has_r_source(coverage: &epiora_core::validation::Coverage) -> bool {
    coverage.fixtures.iter().any(|id| {
        let path = fixtures_root().join(format!("{id}.json"));
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
        let fixture: serde_json::Value =
            serde_json::from_str(&text).unwrap_or_else(|e| panic!("parse {}: {e}", path.display()));
        fixture["source"]["r_version"].is_string()
            || fixture["source"]["packages"]
                .as_object()
                .is_some_and(|p| !p.is_empty())
    })
}

#[test]
fn validation_report_has_every_registry_row() {
    let rows = build_rows(&fixtures_root()).expect("build report rows");
    assert_eq!(
        rows.len(),
        REGISTRY.len(),
        "report rows must be one per REGISTRY entry"
    );
    for (row, coverage) in rows.iter().zip(REGISTRY.iter()) {
        assert_eq!(row.statistic, coverage.statistic);
        assert_eq!(row.class, coverage.class);
        assert!(
            row.worst_error <= coverage.class.tolerance(),
            "{}: worst observed error {} exceeds {:?} tolerance {}",
            coverage.statistic,
            row.worst_error,
            coverage.class,
            coverage.class.tolerance()
        );
    }
}

#[test]
fn json_lists_every_registry_statistic() {
    let text = build_report_json(&fixtures_root(), "test-run").expect("build json");
    let doc: serde_json::Value = serde_json::from_str(&text).expect("parse json");
    assert!(doc["engine_version"].is_string(), "no engine_version");
    assert!(doc["commit"].is_string(), "no commit");
    assert_eq!(
        doc["run_url"].as_str(),
        Some("test-run"),
        "run_url not passed through"
    );
    let stats = doc["statistics"]
        .as_array()
        .expect("statistics is not an array");
    assert_eq!(
        stats.len(),
        REGISTRY.len(),
        "json statistics must be one per REGISTRY entry"
    );
    for (entry, coverage) in stats.iter().zip(REGISTRY.iter()) {
        assert_eq!(entry["id"].as_str(), Some(coverage.statistic));
        assert_eq!(
            entry["class"],
            serde_json::to_value(coverage.class).expect("class to json"),
            "{}: wrong class",
            coverage.statistic
        );
        assert!(
            entry["method"].as_str().is_some_and(|m| !m.is_empty()),
            "{}: no method",
            coverage.statistic
        );
        if has_r_source(coverage) {
            assert!(
                entry["references"]["r"].is_string(),
                "{}: no R reference",
                coverage.statistic
            );
        } else {
            assert!(
                entry["references"].get("r").is_none(),
                "{}: unexpected R reference",
                coverage.statistic
            );
        }
        assert_eq!(
            entry["cases"].as_u64(),
            Some(coverage.fixtures.len() as u64),
            "{}: wrong case count",
            coverage.statistic
        );
        assert!(
            entry["worst_error"].is_number(),
            "{}: no measured worst_error",
            coverage.statistic
        );
    }
    // The seeded golden behind `calc.random_numbers.values[]` has no
    // R generator — its entry must carry no `r` key rather than the
    // empty `": "` shell.
    let random_numbers = stats
        .iter()
        .find(|e| e["id"].as_str() == Some("calc.random_numbers.values[]"))
        .expect("no calc.random_numbers.values[] entry");
    assert!(
        random_numbers["references"].get("r").is_none(),
        "calc.random_numbers.values[] must not carry an R reference"
    );
}

#[test]
fn markdown_output_unchanged() {
    let md = build_report(&fixtures_root(), "test-run", "not measured", "not measured")
        .expect("build report");
    // The v0.2/v1.0 format this task must not touch: every byte that
    // does not come from the build-time SHA or the call arguments is
    // asserted verbatim.
    assert_eq!(
        &md[.."# Epiora v0.2 validation report\n\nGenerated by `validation-report` (v0.2 Task 13); every row is measured by running the corpus.\n\n".len()],
        "# Epiora v0.2 validation report\n\nGenerated by `validation-report` (v0.2 Task 13); every row is measured by running the corpus.\n\n",
        "report intro changed"
    );
    assert!(md.contains("- Commit: `"), "commit bullet missing");
    assert!(
        md.contains(
            "- CI run: test-run\n- Optimised engine `.wasm` after `gzip -9`: not measured bytes \
             (budget 409,600)\n- Chromium bench median (1,000,000 rows, `datasetFromColumns` + \
             stratified `tables`): not measured ms (budget < 1000 ms)\n- Epidemiologist adviser \
             sign-off: pending (required before v1.0, platform §12.9)\n"
        ),
        "header bullets changed"
    );
    assert!(
        md.contains("\n## Corpus coverage\n\nOne row per `validation::REGISTRY` statistic;"),
        "coverage preamble changed"
    );
    assert!(
        md.contains(
            "| Procedure | Statistic | Reference | Class | Tolerance | Worst relative error \
             | Fixtures |\n|---|---|---|---|---|---|---|\n"
        ),
        "column header changed"
    );
    assert!(
        md.contains("\n## Epi Info 7 check\n"),
        "ei7 section missing"
    );
    assert!(
        md.contains("\n## OpenEpi check\n"),
        "openepi section missing"
    );
    // One table row per registry statistic, in registry order.
    let table_start = md
        .find("|---|---|---|---|---|---|---|\n")
        .map(|i| i + "|---|---|---|---|---|---|---|\n".len())
        .expect("coverage table missing");
    for (offset, coverage) in REGISTRY.iter().enumerate() {
        let family = coverage
            .statistic
            .split('.')
            .next()
            .unwrap_or(coverage.statistic);
        let row_start = format!("| {family} | {} |", coverage.statistic);
        assert!(
            md[table_start..].contains(&row_start),
            "registry row {} ({}) missing from the table",
            offset,
            coverage.statistic
        );
    }
}

#[test]
fn report_has_openepi_column() {
    let md = build_report(&fixtures_root(), "test-run", "not measured", "not measured")
        .expect("build report");
    assert!(
        md.contains("## OpenEpi check"),
        "report has no OpenEpi check section"
    );
    assert!(
        md.contains("| Calculator | OpenEpi |"),
        "OpenEpi section has no OpenEpi column"
    );
    // One row per captured calculator file.
    let dir = fixtures_root().join("openepi");
    let skip = [
        "cases.json",
        "labels.json",
        "package.json",
        "package-lock.json",
    ];
    for entry in std::fs::read_dir(&dir).expect("read openepi dir") {
        let path = entry.expect("dir entry").path();
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let name = path.file_name().expect("file name").to_string_lossy();
        if skip.contains(&name.as_ref()) {
            continue;
        }
        let stem = path.file_stem().expect("file stem").to_string_lossy();
        assert!(
            md.contains(&format!("| {stem} |")),
            "no OpenEpi row for {stem}"
        );
    }
}
